-- Migration 001: Roles, station admins, admin updates
-- Run in Supabase Dashboard → SQL Editor

-- ─── Station admin accounts ──────────────────────────────────────────────────
-- Managed by super admins only. No self-registration.
create table if not exists public.station_admins (
  id uuid primary key default gen_random_uuid(),
  station_id uuid not null references public.stations(id) on delete cascade,
  email text not null,
  -- bcrypt hash (cost ≥ 12) stored by the server layer; never plaintext
  password_hash text not null,
  display_name text not null default '',
  is_active boolean not null default true,
  created_by text not null default 'super_admin', -- audit trail
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists station_admins_email_unique on public.station_admins (lower(email));
create index if not exists station_admins_station_idx on public.station_admins (station_id);

-- ─── Admin fuel updates (separate from community reports) ───────────────────
-- A station admin's active update takes precedence over community reports.
-- Expiry is enforced via created_at + 3-hour window; no cleanup job needed.
create table if not exists public.admin_updates (
  id bigint generated by default as identity primary key,
  station_id uuid not null references public.stations(id) on delete cascade,
  admin_id uuid not null references public.station_admins(id) on delete cascade,
  fuel text not null check (fuel in ('Petrol','Diesel')),
  status text not null check (status in ('Available','Low','No fuel')),
  -- Note: queue is intentionally omitted — admins confirm fuel availability only
  created_at timestamptz not null default now()
);
create index if not exists admin_updates_station_fuel_time_idx
  on public.admin_updates (station_id, fuel, created_at desc);

-- ─── Super admin credentials ─────────────────────────────────────────────────
-- Single table. Seed one row manually via the SQL editor after migration.
create table if not exists public.super_admins (
  id uuid primary key default gen_random_uuid(),
  email text not null,
  password_hash text not null,
  created_at timestamptz not null default now()
);
create unique index if not exists super_admins_email_unique on public.super_admins (lower(email));

-- ─── RLS ─────────────────────────────────────────────────────────────────────
alter table public.station_admins enable row level security;
alter table public.admin_updates enable row level security;
alter table public.super_admins enable row level security;

-- All access goes through the service_role (Next.js API routes only)
revoke all on public.station_admins, public.admin_updates, public.super_admins
  from anon, authenticated;
grant all on public.station_admins, public.admin_updates, public.super_admins
  to service_role;
grant usage, select on all sequences in schema public to service_role;

-- ─── RPC: submit_admin_update ─────────────────────────────────────────────────
-- Called by station-admin API route. Verifies admin is active and owns the station.
create or replace function public.submit_admin_update(
  p_admin_id uuid,
  p_station_id uuid,
  p_fuel text,
  p_status text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_admin public.station_admins%rowtype;
  v_created_at timestamptz := now();
begin
  select * into v_admin
    from public.station_admins
    where id = p_admin_id
      and station_id = p_station_id
      and is_active = true;

  if not found then
    raise exception 'ADMIN_NOT_AUTHORISED';
  end if;

  if p_fuel not in ('Petrol','Diesel') then
    raise exception 'INVALID_FUEL';
  end if;

  if p_status not in ('Available','Low','No fuel') then
    raise exception 'INVALID_STATUS';
  end if;

  insert into public.admin_updates (station_id, admin_id, fuel, status, created_at)
    values (p_station_id, p_admin_id, p_fuel, p_status, v_created_at);

  return jsonb_build_object(
    'ok', true,
    'fuel', p_fuel,
    'status', p_status,
    'createdAt', v_created_at
  );
end;
$$;

revoke all on function public.submit_admin_update(uuid,uuid,text,text)
  from public, anon, authenticated;
grant execute on function public.submit_admin_update(uuid,uuid,text,text)
  to service_role;

