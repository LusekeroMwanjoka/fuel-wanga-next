-- Run once in Supabase Dashboard → SQL Editor.
create extension if not exists pgcrypto;

create table if not exists public.stations (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(btrim(name)) between 3 and 100),
  district text not null check (district in (
    'Balaka','Blantyre','Chikwawa','Chiradzulu','Chitipa','Dedza','Dowa','Karonga',
    'Kasungu','Likoma','Lilongwe','Machinga','Mangochi','Mchinji','Mulanje','Mwanza',
    'Mzimba','Neno','Nkhata Bay','Nkhotakota','Nsanje','Ntcheu','Ntchisi','Phalombe',
    'Rumphi','Salima','Thyolo','Zomba'
  )),
  area text not null default '',
  source text,
  source_url text,
  source_checked_at date,
  latitude double precision,
  longitude double precision,
  coordinate_source text,
  coordinate_source_url text,
  coordinates_checked_at date,
  check ((latitude is null and longitude is null) or (latitude between -90 and 90 and longitude between -180 and 180)),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists stations_name_district_unique on public.stations (lower(name), lower(district));
create index if not exists stations_district_name_idx on public.stations (district, name);

create table if not exists public.reports (
  id bigint generated by default as identity primary key,
  station_id uuid not null references public.stations(id) on delete cascade,
  fuel text not null check (fuel in ('Petrol','Diesel','Both')),
  status text not null check (status in ('Available','Low','No fuel')),
  queue text not null check (queue in ('No queue update','No queue','Short queue','Medium queue','Long queue')),
  reporter_key uuid not null,
  created_at timestamptz not null default now()
);
create index if not exists reports_station_time_idx on public.reports (station_id, created_at desc);

-- Sliding 15-minute per-device/report limit, enforced atomically in PostgreSQL.
create table if not exists public.report_limits (
  station_id uuid not null references public.stations(id) on delete cascade,
  reporter_key uuid not null,
  last_report_at timestamptz not null default now(),
  primary key (station_id, reporter_key)
);

-- Public visitors use only the Next.js API. No browser role can read/write these tables.
alter table public.stations enable row level security;
alter table public.reports enable row level security;
alter table public.report_limits enable row level security;
revoke all on public.stations, public.reports, public.report_limits from anon, authenticated;
grant all on public.stations, public.reports, public.report_limits to service_role;
grant usage, select on all sequences in schema public to service_role;

create or replace function public.submit_station_report(
  p_station_id uuid, p_fuel text, p_status text, p_queue text, p_reporter_key uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_allowed uuid;
  v_confirmations integer;
  v_created_at timestamptz := now();
begin
  if p_fuel not in ('Petrol','Diesel','Both') or p_status not in ('Available','Low','No fuel')
     or p_queue not in ('No queue update','No queue','Short queue','Medium queue','Long queue') then
    raise exception 'INVALID_REPORT';
  end if;
  if not exists (select 1 from public.stations where id=p_station_id) then
    raise exception 'STATION_NOT_FOUND';
  end if;
  insert into public.report_limits(station_id,reporter_key,last_report_at)
    values(p_station_id,p_reporter_key,v_created_at)
    on conflict(station_id,reporter_key) do update set last_report_at=excluded.last_report_at
      where public.report_limits.last_report_at <= v_created_at - interval '15 minutes'
    returning station_id into v_allowed;
  if v_allowed is null then raise exception 'REPORT_RATE_LIMIT'; end if;
  insert into public.reports(station_id,fuel,status,queue,reporter_key,created_at)
    values(p_station_id,p_fuel,p_status,p_queue,p_reporter_key,v_created_at);
  select count(distinct reporter_key)::integer into v_confirmations from public.reports
    where station_id=p_station_id and fuel=p_fuel and status=p_status and created_at >= v_created_at - interval '3 hours';
  return jsonb_build_object('ok',true,'createdAt',v_created_at,'confirmations',v_confirmations);
end;
$$;

revoke all on function public.submit_station_report(uuid,text,text,text,uuid) from public, anon, authenticated;
grant execute on function public.submit_station_report(uuid,text,text,text,uuid) to service_role;

